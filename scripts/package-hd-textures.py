"""Build an editable PNG texture pack and its optional built-in UV catalogue."""
import argparse
import hashlib
import json
from pathlib import Path
import zipfile


def manifests(source):
    records={}
    for mode in ('arcade','simulation'):
        for path in sorted((source/mode/'generated-world').glob('*/pack.txt')):
            text=path.read_text();header=text.splitlines()[0].split()
            if len(header)!=2 or header[0] not in ('GT2-GENERATED-WORLD-1','GT2-GENERATED-WORLD-2'):raise ValueError('Invalid registration')
            key=(path.parent.name,header[1])
            if key in records and records[key]!=text:raise ValueError('Conflicting registration')
            records[key]=text
    if not records:raise ValueError('No texture registrations found')
    return records


def catalogue(source,output):
    out=['// Generated by scripts/package-hd-textures.py --catalogue. Do not edit UV registrations.',
         '#pragma once','#include <string_view>','namespace gt2::generated {',
         'inline std::string_view BuiltinTextureManifest(std::string_view course,std::string_view hash) {']
    for (course,digest),text in sorted(manifests(source).items()):
        out.append('if(course=='+json.dumps(course)+' && hash=='+json.dumps(digest)+') return')
        out.extend(json.dumps(line+'\n') for line in text.splitlines());out[-1]+=';'
    out+=['return {};','}','}'];output.parent.mkdir(parents=True,exist_ok=True);output.write_text('\n'.join(out)+'\n')


def payload(source,png_only=False):
    result={}
    for mode in ('arcade','simulation'):
        root=source/mode/'generated-world'
        if not root.is_dir():continue
        def add(path):
            if not path.resolve().is_relative_to(root.resolve()):raise ValueError('Texture reference escapes pack')
            if path.is_file():result['textures/'+mode+'/'+path.relative_to(root).as_posix()]=path
        for path in sorted(root.glob('*/pack.txt')):
            for line in path.read_text().splitlines()[1:]:
                if not line or line.startswith('#'):continue
                fields=line.split()
                if len(fields)<7:raise ValueError('Invalid texture registration')
                name=fields[6]
                if Path(name).name!=name or not name.endswith('.png'):raise ValueError('Invalid texture filename')
                image=path.parent/name
                if not image.is_file():image=root/'_shared'/name
                add(image)
        for sub in ('_shared','_hud','_sponsors'):
            for path in sorted((root/sub).glob('*.png')):add(path)
        if not png_only:
            for path in sorted((root/'_gpu').glob('*.astc')):add(path)
    if not result:raise ValueError('Empty texture pack')
    return result


def build(source,output,png_only=False):
    files=payload(source,png_only);output.parent.mkdir(parents=True,exist_ok=True)
    with zipfile.ZipFile(output,'x',compression=zipfile.ZIP_STORED,allowZip64=True) as archive:
        for name,path in sorted(files.items()):archive.write(path,name)
        archive.writestr('README.txt','Copy textures beside the arcade and simulation folders in the game data folder. Enable HD textures in the VR/graphics menu. Edit or delete PNG images; missing or invalid replacements use original game textures. Restart the game after file changes. Keep image dimensions and alpha. _gpu is an optional content-hash-checked Quest cache; edited images never use stale cache. Requires the matching updated player; public 0.9.2 is not compatible.\n')
    with zipfile.ZipFile(output) as archive:
        if archive.testzip():raise ValueError('Corrupt texture archive')
    print(f'Pack verified: {len(files)} image/cache files, {output.stat().st_size} bytes: {output}')

if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--source',required=True,type=Path)
    parser.add_argument('--output',type=Path);parser.add_argument('--catalogue',type=Path);parser.add_argument('--png-only',action='store_true');args=parser.parse_args()
    if args.catalogue:catalogue(args.source,args.catalogue)
    if args.output:build(args.source,args.output,args.png_only)
    if not args.output and not args.catalogue:parser.error('Choose --output or --catalogue')
